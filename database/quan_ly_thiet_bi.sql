SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

CREATE DATABASE IF NOT EXISTS quan_ly_thiet_bi CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE quan_ly_thiet_bi;

DROP TABLE IF EXISTS chi_tiet_kiem_ke, dot_kiem_ke, phieu_thanh_ly, phieu_dieu_dong, bao_duong_sua_chua, chi_tiet_phieu_muon, phieu_muon, thiet_bi_thong_so, thiet_bi, thong_so_loai, loai_thiet_bi, nguoi_dung, phong_ban;

-- 1. Phòng ban
CREATE TABLE phong_ban (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  ten_phong_ban VARCHAR(100) NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_phong_ban_ten (ten_phong_ban)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 2. Người dùng (vai_tro: quan_tri | nhan_vien)
CREATE TABLE nguoi_dung (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  ho_ten VARCHAR(100) NOT NULL,
  ten_dang_nhap VARCHAR(50) NOT NULL,
  mat_khau_hash VARCHAR(255) NOT NULL,
  vai_tro ENUM('quan_tri','nhan_vien') NOT NULL DEFAULT 'nhan_vien',
  phong_ban_id INT UNSIGNED NOT NULL,
  hoat_dong TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_nguoi_dung_ten_dang_nhap (ten_dang_nhap),
  KEY idx_nguoi_dung_phong_ban (phong_ban_id),
  CONSTRAINT fk_nguoi_dung_phong_ban FOREIGN KEY (phong_ban_id) REFERENCES phong_ban (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 3. Loại thiết bị (ky_hieu dùng sinh mã thiết bị; chu_ky_bao_duong_thang là chu kỳ mặc định theo loại)
CREATE TABLE loai_thiet_bi (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  ten_loai VARCHAR(100) NOT NULL,
  ky_hieu VARCHAR(10) NOT NULL,
  chu_ky_bao_duong_thang SMALLINT UNSIGNED NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_loai_thiet_bi_ten (ten_loai),
  UNIQUE KEY uq_loai_thiet_bi_ky_hieu (ky_hieu)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 4. Định nghĩa các thông số kỹ thuật của từng loại
CREATE TABLE thong_so_loai (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  loai_id INT UNSIGNED NOT NULL,
  ten_thong_so VARCHAR(100) NOT NULL,
  don_vi VARCHAR(30) NULL,
  thu_tu SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (id),
  UNIQUE KEY uq_thong_so_loai (loai_id, ten_thong_so),
  CONSTRAINT fk_thong_so_loai_loai FOREIGN KEY (loai_id) REFERENCES loai_thiet_bi (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 5. Thiết bị (tinh_trang: moi | tot | cu | hong; trang_thai: 7 giá trị)
CREATE TABLE thiet_bi (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  ma_thiet_bi VARCHAR(30) NOT NULL,
  ten_thiet_bi VARCHAR(150) NOT NULL,
  loai_id INT UNSIGNED NOT NULL,
  hang VARCHAR(100) NULL,
  model VARCHAR(100) NULL,
  so_serial VARCHAR(100) NULL,
  ngay_nhap DATE NOT NULL,
  phong_ban_id INT UNSIGNED NOT NULL,
  tinh_trang ENUM('moi','tot','cu','hong') NOT NULL DEFAULT 'moi',
  trang_thai ENUM('san_sang','dang_muon','dang_bao_duong','dang_sua_chua','cho_xu_ly','that_lac','da_thanh_ly') NOT NULL DEFAULT 'san_sang',
  chu_ky_bao_duong_thang SMALLINT UNSIGNED NULL,
  ghi_chu TEXT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_thiet_bi_ma (ma_thiet_bi),
  KEY idx_thiet_bi_loai (loai_id),
  KEY idx_thiet_bi_phong_ban (phong_ban_id),
  KEY idx_thiet_bi_trang_thai (trang_thai),
  CONSTRAINT fk_thiet_bi_loai FOREIGN KEY (loai_id) REFERENCES loai_thiet_bi (id),
  CONSTRAINT fk_thiet_bi_phong_ban FOREIGN KEY (phong_ban_id) REFERENCES phong_ban (id),
  CONSTRAINT chk_thiet_bi_hong_khong_san_sang CHECK (NOT (tinh_trang = 'hong' AND trang_thai = 'san_sang'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 6. Giá trị thông số kỹ thuật của từng thiết bị
CREATE TABLE thiet_bi_thong_so (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  thiet_bi_id INT UNSIGNED NOT NULL,
  thong_so_id INT UNSIGNED NOT NULL,
  gia_tri VARCHAR(255) NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_thiet_bi_thong_so (thiet_bi_id, thong_so_id),
  CONSTRAINT fk_tbts_thiet_bi FOREIGN KEY (thiet_bi_id) REFERENCES thiet_bi (id) ON DELETE CASCADE,
  CONSTRAINT fk_tbts_thong_so FOREIGN KEY (thong_so_id) REFERENCES thong_so_loai (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 7. Phiếu mượn (trang_thai: cho_duyet | da_duyet | da_tra | tu_choi; "quá hạn" tính từ han_tra, không lưu)
CREATE TABLE phieu_muon (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  ma_phieu VARCHAR(30) NOT NULL,
  nguoi_muon_id INT UNSIGNED NOT NULL,
  nguoi_lap_id INT UNSIGNED NOT NULL,
  ngay_muon DATE NOT NULL,
  han_tra DATE NOT NULL,
  ngay_tra DATE NULL,
  nguoi_duyet_id INT UNSIGNED NULL,
  thoi_diem_duyet DATETIME NULL,
  trang_thai ENUM('cho_duyet','da_duyet','da_tra','tu_choi') NOT NULL DEFAULT 'cho_duyet',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_phieu_muon_ma (ma_phieu),
  KEY idx_phieu_muon_nguoi_muon (nguoi_muon_id),
  KEY idx_phieu_muon_trang_thai (trang_thai),
  CONSTRAINT fk_phieu_muon_nguoi_muon FOREIGN KEY (nguoi_muon_id) REFERENCES nguoi_dung (id),
  CONSTRAINT fk_phieu_muon_nguoi_lap FOREIGN KEY (nguoi_lap_id) REFERENCES nguoi_dung (id),
  CONSTRAINT fk_phieu_muon_nguoi_duyet FOREIGN KEY (nguoi_duyet_id) REFERENCES nguoi_dung (id),
  CONSTRAINT chk_phieu_muon_han_tra CHECK (han_tra >= ngay_muon)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 8. Chi tiết phiếu mượn (một phiếu mượn nhiều thiết bị)
CREATE TABLE chi_tiet_phieu_muon (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  phieu_id INT UNSIGNED NOT NULL,
  thiet_bi_id INT UNSIGNED NOT NULL,
  tinh_trang_khi_tra ENUM('moi','tot','cu','hong') NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_chi_tiet_phieu_muon (phieu_id, thiet_bi_id),
  KEY idx_ctpm_thiet_bi (thiet_bi_id),
  CONSTRAINT fk_ctpm_phieu FOREIGN KEY (phieu_id) REFERENCES phieu_muon (id),
  CONSTRAINT fk_ctpm_thiet_bi FOREIGN KEY (thiet_bi_id) REFERENCES thiet_bi (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 9. Bảo dưỡng - sửa chữa (loai_hinh: bao_duong | sua_chua)
CREATE TABLE bao_duong_sua_chua (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  thiet_bi_id INT UNSIGNED NOT NULL,
  loai_hinh ENUM('bao_duong','sua_chua') NOT NULL,
  ngay_bat_dau DATE NOT NULL,
  ngay_hoan_tat DATE NULL,
  van_de TEXT NULL,
  noi_dung_xu_ly TEXT NULL,
  chi_phi DECIMAL(14,0) NOT NULL DEFAULT 0,
  ket_qua ENUM('dang_thuc_hien','thanh_cong','khong_thanh_cong') NOT NULL DEFAULT 'dang_thuc_hien',
  tinh_trang_sau_xu_ly ENUM('moi','tot','cu','hong') NULL,
  ngay_bao_duong_ke_tiep DATE NULL,
  nguoi_tao_id INT UNSIGNED NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_bdsc_thiet_bi (thiet_bi_id),
  KEY idx_bdsc_ke_tiep (ngay_bao_duong_ke_tiep),
  CONSTRAINT fk_bdsc_thiet_bi FOREIGN KEY (thiet_bi_id) REFERENCES thiet_bi (id),
  CONSTRAINT fk_bdsc_nguoi_tao FOREIGN KEY (nguoi_tao_id) REFERENCES nguoi_dung (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 10. Đợt kiểm kê (phong_ban_id NULL = toàn công ty)
CREATE TABLE dot_kiem_ke (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  ma_dot VARCHAR(30) NOT NULL,
  ten_dot VARCHAR(150) NOT NULL,
  phong_ban_id INT UNSIGNED NULL,
  ngay_kiem_ke DATE NOT NULL,
  nguoi_thuc_hien_id INT UNSIGNED NOT NULL,
  trang_thai ENUM('dang_kiem_ke','hoan_tat') NOT NULL DEFAULT 'dang_kiem_ke',
  bien_ban TEXT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_dot_kiem_ke_ma (ma_dot),
  CONSTRAINT fk_dkk_phong_ban FOREIGN KEY (phong_ban_id) REFERENCES phong_ban (id),
  CONSTRAINT fk_dkk_nguoi_thuc_hien FOREIGN KEY (nguoi_thuc_hien_id) REFERENCES nguoi_dung (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 11. Chi tiết kiểm kê (ket_qua NULL = chưa kiểm; thiet_bi_id NULL = thiết bị thừa chưa có hồ sơ)
CREATE TABLE chi_tiet_kiem_ke (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  dot_id INT UNSIGNED NOT NULL,
  thiet_bi_id INT UNSIGNED NULL,
  ket_qua ENUM('dung','thieu','thua','sai_vi_tri','sai_tinh_trang') NULL,
  phong_ban_he_thong_id INT UNSIGNED NULL,
  phong_ban_thuc_te_id INT UNSIGNED NULL,
  tinh_trang_he_thong ENUM('moi','tot','cu','hong') NULL,
  tinh_trang_thuc_te ENUM('moi','tot','cu','hong') NULL,
  mo_ta_thiet_bi_thua VARCHAR(255) NULL,
  ghi_chu VARCHAR(255) NULL,
  da_xu_ly TINYINT(1) NOT NULL DEFAULT 0,
  PRIMARY KEY (id),
  UNIQUE KEY uq_ctkk_dot_thiet_bi (dot_id, thiet_bi_id),
  KEY idx_ctkk_thiet_bi (thiet_bi_id),
  CONSTRAINT fk_ctkk_dot FOREIGN KEY (dot_id) REFERENCES dot_kiem_ke (id),
  CONSTRAINT fk_ctkk_thiet_bi FOREIGN KEY (thiet_bi_id) REFERENCES thiet_bi (id),
  CONSTRAINT fk_ctkk_pb_he_thong FOREIGN KEY (phong_ban_he_thong_id) REFERENCES phong_ban (id),
  CONSTRAINT fk_ctkk_pb_thuc_te FOREIGN KEY (phong_ban_thuc_te_id) REFERENCES phong_ban (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 12. Phiếu điều động (mỗi phiếu một thiết bị)
CREATE TABLE phieu_dieu_dong (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  ma_phieu VARCHAR(30) NOT NULL,
  thiet_bi_id INT UNSIGNED NOT NULL,
  phong_ban_di_id INT UNSIGNED NOT NULL,
  phong_ban_den_id INT UNSIGNED NOT NULL,
  ly_do VARCHAR(255) NOT NULL,
  ngay_dieu_dong DATE NOT NULL,
  nguoi_lap_id INT UNSIGNED NOT NULL,
  nguoi_duyet_id INT UNSIGNED NULL,
  thoi_diem_duyet DATETIME NULL,
  trang_thai ENUM('cho_duyet','da_duyet','tu_choi') NOT NULL DEFAULT 'cho_duyet',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_phieu_dieu_dong_ma (ma_phieu),
  KEY idx_pdd_thiet_bi (thiet_bi_id),
  CONSTRAINT fk_pdd_thiet_bi FOREIGN KEY (thiet_bi_id) REFERENCES thiet_bi (id),
  CONSTRAINT fk_pdd_phong_ban_di FOREIGN KEY (phong_ban_di_id) REFERENCES phong_ban (id),
  CONSTRAINT fk_pdd_phong_ban_den FOREIGN KEY (phong_ban_den_id) REFERENCES phong_ban (id),
  CONSTRAINT fk_pdd_nguoi_lap FOREIGN KEY (nguoi_lap_id) REFERENCES nguoi_dung (id),
  CONSTRAINT fk_pdd_nguoi_duyet FOREIGN KEY (nguoi_duyet_id) REFERENCES nguoi_dung (id),
  CONSTRAINT chk_pdd_khac_phong_ban CHECK (phong_ban_di_id <> phong_ban_den_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 13. Phiếu thanh lý (mỗi phiếu một thiết bị; hinh_thuc: ban | tieu_huy | tan_dung_linh_kien)
CREATE TABLE phieu_thanh_ly (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  ma_phieu VARCHAR(30) NOT NULL,
  thiet_bi_id INT UNSIGNED NOT NULL,
  ly_do VARCHAR(255) NOT NULL,
  hinh_thuc ENUM('ban','tieu_huy','tan_dung_linh_kien') NOT NULL,
  gia_tri_thu_hoi DECIMAL(14,0) NOT NULL DEFAULT 0,
  ngay_thanh_ly DATE NOT NULL,
  nguoi_lap_id INT UNSIGNED NOT NULL,
  nguoi_duyet_id INT UNSIGNED NULL,
  thoi_diem_duyet DATETIME NULL,
  trang_thai ENUM('cho_duyet','da_duyet','tu_choi') NOT NULL DEFAULT 'cho_duyet',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_phieu_thanh_ly_ma (ma_phieu),
  KEY idx_ptl_thiet_bi (thiet_bi_id),
  CONSTRAINT fk_ptl_thiet_bi FOREIGN KEY (thiet_bi_id) REFERENCES thiet_bi (id),
  CONSTRAINT fk_ptl_nguoi_lap FOREIGN KEY (nguoi_lap_id) REFERENCES nguoi_dung (id),
  CONSTRAINT fk_ptl_nguoi_duyet FOREIGN KEY (nguoi_duyet_id) REFERENCES nguoi_dung (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

SET FOREIGN_KEY_CHECKS = 1;



